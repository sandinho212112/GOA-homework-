#1) ივარჯიშეთ .upper() / .lower() / .capitalize() და ახსენით კომენტარის სახით თითოეული ფუნქციის დანიშნულება (ახსენით რა არის dot notation)
name= "sandro"
#Sandro
print(name.upper())
#sandro
print(name.lower())
#SANDRO
print(name.capitalize())

#2) ივარჯიშეთ წინა მასალაზე (append / pop / insert) კომენტარებით ახსენით თითოეული ფუნქციის დანიშნულება და გააკეთეთ 3-3-3 მაგალითი
#append
names = ["gela", "vano", "zvingo", "jeksona"]
names.append["sandrika"]
print(names)
#pop
names = ["gela", "vano", "zvingo", "jeksona"]
names.pop()
print(names)
#insert
names = ["gela", "vano", "zvingo", "jeksona"]
names.insert(3, "tolika")
print(names)